class ProxyContext:
    """Context manager for associating the current active command/agent with proxy requests across processes."""
    def __init__(self, project: str, agent_id: str = "primary_agent"):
        self.project = (project or "default").strip().lower()
        self.agent_id = agent_id or "primary_agent"

    def __enter__(self):
        _current_active_projects.append((self.project, self.agent_id))
        try:
            ctx_path = _get_active_context_file()
            tmp_path = ctx_path + f".tmp_{os.getpid()}"
            with open(tmp_path, "w", encoding="utf-8") as f:
                json.dump({
                    "project": self.project,
                    "agent_id": self.agent_id,
                    "timestamp": time.time()
                }, f)
            os.replace(tmp_path, ctx_path)
        except Exception:
            pass
        return self

    def __exit__(self, exc_type, exc_val, exc_tb):
        if (self.project, self.agent_id) in _current_active_projects:
            _current_active_projects.remove((self.project, self.agent_id))
        try:
            ctx_path = _get_active_context_file()
            if os.path.exists(ctx_path) and not _current_active_projects:
                if _active_ui_context:
                    # Restore persistent UI context
                    with open(ctx_path, "w", encoding="utf-8") as f:
                        json.dump({
                            "project": _active_ui_context[0],
                            "agent_id": _active_ui_context[1],
                            "timestamp": time.time(),
                            "persistent": True
                        }, f)
                else:
                    try:
                        os.remove(ctx_path)
                    except Exception:
                        pass
        except Exception:
            pass

def get_current_active_context() -> Tuple[str, str]:
    if _current_active_projects:
        return _current_active_projects[-1]
    if _active_ui_context:
        return _active_ui_context
    try:
        ctx_path = _get_active_context_file()
        if os.path.exists(ctx_path):
            with open(ctx_path, "r", encoding="utf-8") as f:
                data = json.load(f)
                is_persistent = bool(data.get("persistent", False))
                is_recent = (time.time() - float(data.get("timestamp", 0)) < 180)
                if is_persistent or is_recent:
                    p = data.get("project")
                    a = data.get("agent_id")
                    if p:
                        return p.strip().lower(), (a or "primary_agent").strip()
    except Exception:
        pass
    default_proj = os.getenv("PROXSYNTH_PROJECT", "default").strip().lower()
    return default_proj, "primary_agent"


def _get_active_cookies_for_host(host: str, project: str) -> Dict[str, str]:
    """Retrieves session cookies registered for the given target host."""
    cookies = {}
    try:
        db = SessionLocal()
        try:
            sessions = db.query(ActiveSession).filter(ActiveSession.is_active == True).all()
            target_host = host.split(":")[0].lower()
            for s in sessions:
                stored_dom = (s.domain or "").lower().split(":")[0].strip("/")
                is_match = (
                    target_host == stored_dom or
                    target_host.endswith("." + stored_dom) or
                    stored_dom.endswith("." + target_host) or
                    (stored_dom in target_host and len(stored_dom) > 3)
                )
                if is_match:
                    try:
                        state_data = s.get_decrypted_state()
                        for c in state_data.get("cookies", []):
                            cn = c.get("name")
                            cv = c.get("value")
                            if cn and cv:
                                cookies[cn] = cv
                    except Exception:
                        pass
        finally:
            db.close()
    except Exception:
        pass
    return cookies


