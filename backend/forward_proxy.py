async def start_forward_proxy(host: Optional[str] = None, port: Optional[int] = None) -> asyncio.Server:
    """Starts the Proxsynth Forward Proxy server asynchronously."""
    global _proxy_server, _is_proxy_running, _proxy_host, _proxy_port
    if _is_proxy_running and _proxy_server:
        return _proxy_server

    _proxy_host = host or os.getenv("PROXSYNTH_PROXY_HOST", "127.0.0.1")
    _proxy_port = port or int(os.getenv("PROXSYNTH_PROXY_PORT", "8088"))
    os.environ["PROXSYNTH_IS_PROXY"] = "1"

    _proxy_server = await asyncio.start_server(_handle_client_connection, _proxy_host, _proxy_port)
    _is_proxy_running = True
    return _proxy_server


async def stop_forward_proxy():
    """Stops the Proxsynth Forward Proxy server."""
    global _proxy_server, _is_proxy_running
    if _proxy_server:
        _proxy_server.close()
        await _proxy_server.wait_closed()
        _proxy_server = None
    _is_proxy_running = False


async def ensure_forward_proxy_running(host: Optional[str] = None, port: Optional[int] = None) -> bool:
    """Ensures the Proxsynth Forward Proxy server is actively running. Starts it if not listening."""
    p_host = host or os.getenv("PROXSYNTH_PROXY_HOST", "127.0.0.1")
    p_port = port or int(os.getenv("PROXSYNTH_PROXY_PORT", "8088"))

    # Test if port is already listening and responsive
    try:
        _, writer = await asyncio.wait_for(asyncio.open_connection(p_host, p_port), timeout=0.2)
        writer.close()
        await writer.wait_closed()
        return True
    except Exception:
        pass

    # Start forward proxy server in background
    try:
        await start_forward_proxy(p_host, p_port)
        return True
    except OSError:
        # Port might have been bound concurrently by another process
        return True
    except Exception:
        return False

